#!/usr/bin/env bash
# Makes the site see the visitor's real IP behind ArvanCloud (instead of the CDN's IP).
# Run as root on the server:  bash deploy/real-ip.sh
# Arvan sends the visitor IP in X-Forwarded-For. nginx trusts that header only when the
# request really comes from an Arvan address, then hands the real IP to the site.
# Safe: backs up the nginx config and restores it if `nginx -t` fails.
set -eu
[ "$(id -u)" = 0 ] || { echo "Run as root."; exit 1; }
APP_DIR=/var/www/anitale
IPS=/tmp/arvan-ips.txt
curl -fsS --max-time 20 https://www.arvancloud.ir/en/ips.txt -o "$IPS" || { echo "Could not download the Arvan IP list. Check this server can reach arvancloud.ir."; exit 1; }
grep -E '^[0-9]{1,3}(\.[0-9]{1,3}){3}(/[0-9]{1,2})?$' "$IPS" > "$IPS.v4" || true
N=$(wc -l < "$IPS.v4")
[ "$N" -ge 5 ] || { echo "The IP list looks wrong ($N lines). Stopping."; exit 1; }
echo "Arvan ranges: $N"

SITE=${SITE:-$(grep -rlE 'proxy_pass[[:space:]]+http://(127\.0\.0\.1|localhost):3000' /etc/nginx 2>/dev/null | head -1)}
[ -n "$SITE" ] || { echo "Could not find the nginx file that proxies to port 3000. Run: grep -rn 3000 /etc/nginx   and send me the output."; exit 1; }
echo "Site config: $SITE"
BK=/root/nginx-backup-$(date +%s); mkdir -p "$BK"; cp -a /etc/nginx/. "$BK/"; echo "Backup: $BK"

{
  echo "# Generated by deploy/real-ip.sh: trust X-Forwarded-For only from ArvanCloud"
  while read -r r; do echo "set_real_ip_from $r;"; done < "$IPS.v4"
  echo "real_ip_header X-Forwarded-For;"
  echo "real_ip_recursive on;"
} > /etc/nginx/conf.d/arvan-realip.conf

# pass the (now real) client address on to the site
sed -i 's|proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;|proxy_set_header X-Forwarded-For $remote_addr;|' "$SITE"

if nginx -t 2>&1; then
  systemctl reload nginx; echo "nginx reloaded."
else
  echo "nginx config test FAILED, restoring backup."
  rm -f /etc/nginx/conf.d/arvan-realip.conf; cp -a "$BK/." /etc/nginx/; nginx -t && systemctl reload nginx; exit 1
fi

# the site must trust one proxy hop (nginx) to read that header
ENVF=$APP_DIR/server/.env
if [ -f "$ENVF" ]; then
  if grep -q '^TRUST_PROXY=' "$ENVF"; then sed -i 's/^TRUST_PROXY=.*/TRUST_PROXY=1/' "$ENVF"; else printf '\nTRUST_PROXY=1\n' >> "$ENVF"; fi
  echo "TRUST_PROXY=1 set in server/.env"
  systemctl restart anitale; sleep 3; systemctl is-active anitale
else
  echo "server/.env not found: add TRUST_PROXY=1 to it yourself, then restart anitale."
fi
echo
echo "Check: open the site from your phone, then run:  tail -n 2 /var/log/nginx/access.log"
echo "The first address on each line should now be YOUR IP, not 185.215.232.x"
